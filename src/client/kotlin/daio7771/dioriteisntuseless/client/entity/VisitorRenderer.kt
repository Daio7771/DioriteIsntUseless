package daio7771.dioriteisntuseless.client.entity

import com.mojang.blaze3d.vertex.PoseStack
import com.mojang.math.Axis
import daio7771.dioriteisntuseless.Dioriteisntuseless
import daio7771.dioriteisntuseless.entity.UsefulOwnerEntity
import daio7771.dioriteisntuseless.entity.VisitorEntity
import daio7771.dioriteisntuseless.registry.ModEntities
import net.fabricmc.fabric.api.client.rendering.v1.EntityRendererRegistry
import net.minecraft.client.model.PlayerModel
import net.minecraft.client.model.geom.ModelLayers
import net.minecraft.client.model.geom.ModelPart
import net.minecraft.client.renderer.entity.EntityRendererProvider
import net.minecraft.client.renderer.entity.LivingEntityRenderer
import net.minecraft.resources.ResourceLocation
import net.minecraft.util.Mth
import net.minecraft.world.entity.LivingEntity
import kotlin.math.max

/**
 * Draws a visitor with the player model (wide arms, like Steve) and its skin, generated by
 * tools/generate_miner_skin.py and tools/generate_owner_skin.py. Never with a name tag.
 *
 * [limping] (The Miner): his right leg barely bends, and on every stride, as his weight falls on
 * it, he sinks a little and leans to that side. Only while he walks, and smoothly: it follows the
 * walk animation, never jumps.
 */
class VisitorRenderer<T : VisitorEntity>(
    context: EntityRendererProvider.Context,
    private val texture: ResourceLocation,
    private val widthScale: Float = 1f,
    private val heightScale: Float = 1f,
    private val limping: Boolean = false,
) : LivingEntityRenderer<T, PlayerModel<T>>(
    context, VisitorModel(context.bakeLayer(ModelLayers.PLAYER), limping), SHADOW_RADIUS * widthScale,
) {

    override fun getTextureLocation(entity: T): ResourceLocation = texture

    override fun scale(entity: T, poseStack: PoseStack, partialTick: Float) {
        poseStack.scale(PLAYER_SCALE * widthScale, PLAYER_SCALE * heightScale, PLAYER_SCALE * widthScale)
    }

    override fun setupRotations(entity: T, poseStack: PoseStack, ageInTicks: Float, bodyYaw: Float, partialTick: Float) {
        super.setupRotations(entity, poseStack, ageInTicks, bodyYaw, partialTick)
        if (!limping) return
        val speed = entity.walkAnimation.speed(partialTick).coerceAtMost(1f)
        if (speed <= 0f) return
        // The half of each stride when the right foot is on the ground (the same cycle as the legs).
        val weight = max(0f, -Mth.sin(entity.walkAnimation.position(partialTick) * LEG_CYCLE)) * speed
        poseStack.translate(0.0, -(LIMP_DIP * weight).toDouble(), 0.0)
        poseStack.mulPose(Axis.ZP.rotationDegrees(LIMP_LEAN_DEGREES * weight))
    }

    override fun shouldShowName(entity: T): Boolean = false

    /** The player model; limping, with a stiff right leg. */
    private class VisitorModel<T : LivingEntity>(root: ModelPart, private val limping: Boolean) : PlayerModel<T>(root, false) {
        override fun setupAnim(entity: T, limbSwing: Float, limbSwingAmount: Float, ageInTicks: Float, netHeadYaw: Float, headPitch: Float) {
            super.setupAnim(entity, limbSwing, limbSwingAmount, ageInTicks, netHeadYaw, headPitch)
            if (!limping) return
            rightLeg.xRot *= STIFF_LEG
            rightPants.copyFrom(rightLeg)
        }
    }

    companion object {
        /** The same as PlayerRenderer. */
        private const val PLAYER_SCALE = 0.9375f
        private const val SHADOW_RADIUS = 0.5f

        /** HumanoidModel's leg swing frequency. */
        private const val LEG_CYCLE = 0.6662f

        /** How much of its swing the bad leg keeps. */
        private const val STIFF_LEG = 0.35f

        /** At most, in blocks and degrees, with every limping step. */
        private const val LIMP_DIP = 0.06f
        private const val LIMP_LEAN_DEGREES = 4f

        fun init() {
            EntityRendererRegistry.register(ModEntities.THE_MINER) {
                VisitorRenderer(it, Dioriteisntuseless.id("textures/entity/the_miner.png"), limping = true)
            }
            EntityRendererRegistry.register(ModEntities.USEFUL_OWNER) {
                VisitorRenderer(
                    it, Dioriteisntuseless.id("textures/entity/useful_owner.png"),
                    UsefulOwnerEntity.WIDTH_SCALE, UsefulOwnerEntity.HEIGHT_SCALE,
                )
            }
        }
    }
}
